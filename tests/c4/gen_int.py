#!/usr/bin/env python3
"""Generates the C4 interrupt tests (spec 4, 6.1 EI/DI, 7) into build/gen/c4: one program per INT start state K.
The testbench raises INT at the start of state K (counted from the first T1) and holds it until the INTA cycle starts;
during INTA it puts RST 1 on the bus (spec 7). The handler at 0008 writes B (OUT 1), the low byte of the pushed return
address (OUT 2), re-enables interrupts and returns.
Programs (main at 0100, entered by JMP at 0000):
  inr:  LXI SP; MVI B,0; EI; (INR B; NOP) x 60; MOV A,B; OUT 3.  INT at state K is accepted at the end of the first
        instruction after EI whose last state is >= K (EI itself never: spec 6.1, ALP p.3-24). Expected: B at that point, the address of
        the next instruction, then OUT 3 with B = 60. Covers EI's delayed effect, RST via INTA and INT at every state of many instructions.
  noei: the same without EI: INT is ignored, only OUT 3 (B = 60).
  di:   EI; DI directly after: INT is ignored (DI takes effect at once).
  halt: LXI SP; MVI B,7; EI; HLT; OUT 3. INT raised while halted (K after the HLT's 7 states): leaves the halt through INTA; return address
        = address after HLT; then OUT 3 with B = 7.
Expected values come from tests/mach80.py's per-instruction state counts (spec 6.1) and the acceptance rule of spec 4/6.1."""
import os, sys
sys.dont_write_bytecode = True
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here + '/..')
import mach80
d = sys.argv[1] if len(sys.argv) > 1 else "build/gen/c4"; os.makedirs(d, exist_ok=True)
HANDLER = ["        .org 0", "        JMP 256", "        .org 8", "        MOV A,B", "        OUT 1", "        POP H", "        PUSH H", "        MOV A,L", "        OUT 2", "        EI", "        RET", "        .org 256"]
def build(prog):
    body = ["LXI SP,0x4800", "MVI B,0" if prog != 'halt' else "MVI B,7"]
    if prog in ('inr', 'halt', 'di'): body.append("EI")
    if prog == 'di': body.append("DI")
    if prog == 'halt': body += ["HLT"]
    else: body += ["INR B", "NOP"] * 60
    return body
def walk(prog):
    """Instruction list [(address, text, first_state, last_state)] of the main flow, JMP at 0 first."""
    m = mach80.Mach(0); lst = []; n = 0
    def run(t):
        nonlocal n
        a = m.pc; c = m.run(t); st = sum(x[3] for x in c); lst.append((a, t, n, n + st - 1)); n += st
    run("JMP 256")
    for t in build(prog): run(t)
    if prog == 'halt': lst[-1] = (lst[-1][0], 'HLT', lst[-1][2], lst[-1][3])      # HLT = 7 states, the 7th is the first TWH
    run("MOV A,B") if prog != 'halt' else None
    return lst
def write(name, prog, exp):
    asm = [f"; C4 {name}, generated by gen_int.py"] + HANDLER + ["        " + t for t in build(prog)] + (["        MOV A,B"] if prog != 'halt' else [])
    asm += ["        OUT 3", "end:    JMP end"]
    open(f"{d}/{name}.asm", "w").write("\n".join(asm) + "\n")
    open(f"{d}/{name}.exp", "w").write("\n".join("%04X" % e for e in exp) + "\n")
ks = {}
for prog in ('inr', 'noei', 'di', 'halt'):
    lst = walk(prog)
    if prog in ('inr',):
        ei = next(i for i, x in enumerate(lst) if x[1] == 'EI'); last = max(x[3] for x in lst)
        for K in list(range(1, 81)) + list(range(300, 332)) + list(range(last - 12, last)):
            acc = next((i for i in range(ei + 1, len(lst)) if lst[i][3] >= K), None)
            if acc is None or lst[acc][1] == 'MOV A,B' and False: continue
            b = sum(1 for x in lst[:acc + 1] if x[1] == 'INR B'); nxt = lst[acc + 1][0] if acc + 1 < len(lst) else None
            if nxt is None: continue
            write(f"int_inr_k{K}", prog, [0x0100 | b, 0x0200 | (nxt & 255), 0x0300 | 60]); ks[f"int_inr_k{K}"] = K
    elif prog in ('noei', 'di'):
        for K in list(range(1, 60, 3)) + [200, 301, 450]:
            write(f"int_{prog}_k{K}", prog, [0x0300 | 60]); ks[f"int_{prog}_k{K}"] = K
    else:
        hl = lst[-1]; hlt_addr = next(x[0] for x in lst if x[1] == 'HLT')
        for K in range(hl[3] + 1, hl[3] + 41):
            write(f"int_halt_k{K}", prog, [0x0100 | 7, 0x0200 | ((hlt_addr + 1) & 255), 0x0300 | 7]); ks[f"int_halt_k{K}"] = K
with open(f"{d}/ks.txt", "w") as f:
    for name, K in ks.items(): f.write(f"{name} {K}\n")
print("wrote", len(ks), "interrupt programs")
