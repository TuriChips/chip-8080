#!/usr/bin/env python3
"""Generates the C1 branch test (spec 6.1: JMP, Jcc, CALL, Ccc, RET, Rcc, RST, PCHL) into build/gen/c1/branch.asm/.exp.
All 8 condition codes x all 16 combinations of the S, Z, P, CY flags (set exactly with POP PSW), each for Jcc, Ccc and Rcc,
taken and not taken, written from spec 6 only. Markers written with OUT: 1 = fell through / returned to the caller,
2 = taken Jcc / the code after a not-taken Rcc, 3 = inside the called subroutine (Ccc). After the flag cases:
JMP, PCHL, CALL/RET with SP checked (OUT of SP = 4800), RST 1..7 (the handler writes the low byte of the pushed return
address, so the pushed PC is checked) and RST 0 (address 0 jumps to main again; a flag in memory tells the second visit;
the return address is popped and written out).
Condition k (NZ Z NC C PO PE P M) is true when: Z=0, Z=1, CY=0, CY=1, P=0, P=1, S=0, S=1 (spec 6.1 CCC table)."""
import os, sys
sys.dont_write_bytecode = True
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here + '/..')
import asm80
d = sys.argv[1] if len(sys.argv) > 1 else "build/gen/c1"; os.makedirs(d, exist_ok=True)
CC = ['NZ', 'Z', 'NC', 'C', 'PO', 'PE', 'P', 'M']
def cond(k, s, z, p, cy): return [not z, z, not cy, cy, not p, p, not s, s][k]
asm = ["; C1 branch group, generated by gen_branch.py", "        .org 0", "        JMP main"]
exp = []
for n in range(1, 8): asm += [f"        .org {8*n}", "        POP H", "        PUSH H", "        MOV A,L", "        OUT 3", "        RET"]
asm += ["        .org 0x100"]
# RST 0: address 0 jumps to main again; main must not reload SP on the second visit, so the pushed return address can be popped
asm += ["main:   LDA 0x4100", "        ORA A", "        JNZ rst0_seen", "        LXI SP,0x4800", "        MVI A,1", "        STA 0x4100", "rst0:   RST 0", "after0: NOP"]
k = 0
def setf(s, z, p, cy):
    f = 0x02 | s << 7 | z << 6 | p << 2 | cy
    return ["        LXI D,%d" % f, "        PUSH D", "        POP PSW"]
lbl = lambda: (globals().__setitem__('k', k + 1), k)[1]
for c in range(8):
    for bits in range(16):
        s, z, p, cy = bits >> 3 & 1, bits >> 2 & 1, bits >> 1 & 1, bits & 1
        t = cond(c, s, z, p, cy); n = lbl()
        asm += setf(s, z, p, cy) + [f"        J{CC[c]} t{n}", "        MVI A,1", "        OUT 1", f"        JMP e{n}", f"t{n}:     MVI A,2", "        OUT 1", f"e{n}:     NOP"]
        exp.append(0x0100 | (2 if t else 1))
        n = lbl()
        asm += setf(s, z, p, cy) + [f"        C{CC[c]} sub", "        MVI A,1", "        OUT 1"]
        exp += ([0x0203] if t else []) + [0x0101]
        n = lbl()
        asm += setf(s, z, p, cy) + [f"        CALL r{n}", "        MVI A,1", "        OUT 1", f"        JMP e{n}", f"r{n}:     R{CC[c]}", "        MVI A,2", "        OUT 2", "        RET", f"e{n}:     NOP"]
        exp += ([] if t else [0x0202]) + [0x0101]
# unconditional
asm += ["        JMP j1", "        MVI A,9", "        OUT 1", "j1:     MVI A,0xB0", "        OUT 1",
        "        LXI H,pch", "        PCHL", "        MVI A,9", "        OUT 1", "pch:    MVI A,0xA0", "        OUT 1",
        "        CALL f1", "        MVI A,0xC0", "        OUT 1", "        JMP n1", "f1:     MVI A,0xC1", "        OUT 1", "        RET", "n1:     LXI H,0", "        DAD SP",
        "        MOV A,H", "        OUT 4", "        MOV A,L", "        OUT 5"]
exp += [0x01B0, 0x01A0, 0x01C1, 0x01C0, 0x0448, 0x0500]
for n in range(1, 8): asm += [f"        RST {n}", f"b{n}:     NOP"]
asm += ["        JMP fin", "rst0_seen:", "        POP H", "        MOV A,H", "        OUT 6", "        MOV A,L", "        OUT 7", "        JMP after0",
        "sub:    MVI A,3", "        OUT 2", "        RET", "fin:    NOP", "end:    JMP end"]
text = asm
labels = {}; asm80.assemble(text, False, labels); asm80.assemble(text, True, labels)
# RST 1..7: handler writes low byte of the return address (address of the instruction after RST n, = label b<n>)
exp += [0x0300 | (labels[f"b{n}"] & 255) for n in range(1, 8)]
# RST 0, second visit: the popped return address is the one after "RST 0" (label after0); the program then continues
# at after0: the order in the trace is: RST 0 happens first (before the flag cases)
ra = labels["after0"]; exp = [0x0600 | (ra >> 8), 0x0700 | (ra & 255)] + exp
open(f"{d}/branch.asm", "w").write("\n".join(text) + "\n")
open(f"{d}/branch.exp", "w").write("\n".join("%04X" % e for e in exp) + "\n")
print("wrote branch:", len(exp), "entries, program top", hex(max(asm80.assemble(text, True, labels))))
