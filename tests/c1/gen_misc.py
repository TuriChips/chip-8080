#!/usr/bin/env python3
"""Generates C1/C5 tests for DAA, INR/DCR (register B and M) and the four rotates into build/gen/c1 (or argv[1]).
A and F are set exactly with LXI D / PUSH D / POP PSW (spec 6.1: POP PSW loads A and S Z AC P CY), so every flag
input is controlled, then the instruction runs and A/B/M and F are written out (OUT 1, OUT 2).
  daa:      A 00..F9 x (CY, AC) in {0,1}^2 (1000 cases). A = FA..FF are skipped until chip-8080#26 is decided.
  inr_b, inr_m, dcr_b, dcr_m: value 00..FF x CY in {0,1} x flag pattern in {S/Z/AC/P all 0, all 1} (1024 cases)
  rlc, rrc, ral, rar: A 00..FF x CY x flag pattern (1024 cases); only CY may change.
Expected values come from tests/model80.py (written from spec 6)."""
import os, sys
sys.dont_write_bytecode = True
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here + '/..')
import model80
d = sys.argv[1] if len(sys.argv) > 1 else "build/gen/c1"; os.makedirs(d, exist_ok=True)
PAT = [0x02, 0xD6]                                    # F bits 7,6,4,2 (S Z AC P) all 0, all 1; bit 1 = 1 as PUSH PSW shows it
def setup(a, f): return [f"        LXI D,{a << 8 | f}", "        PUSH D", "        POP PSW"]
DUMP_F = ["        PUSH PSW", "        POP D", "        MOV A,E", "        OUT 2"]
def write(name, title, asm, exp):
    asm = [f"; {title}, generated by gen_misc.py", "        .org 0", "        LXI SP,0x8000", "        LXI H,0xC000"] + asm + ["end:    JMP end"]
    import asm80; top = max(asm80.assemble(asm, True, {})); assert top < 0x7000, f"{name}: program reaches {top:#x}, into the data/stack area"
    open(f"{d}/{name}.asm", "w").write("\n".join(asm) + "\n"); open(f"{d}/{name}.exp", "w").write("\n".join("%04X" % e for e in exp) + "\n")
# DAA
asm, exp = [], []
for a in range(0xFA):
    for cy in (0, 1):
        for ac in (0, 1):
            f = 0x02 | cy | ac << 4
            asm += setup(a, f) + ["        DAA", "        PUSH PSW", "        POP D", "        MOV A,D", "        OUT 1", "        MOV A,E", "        OUT 2"]
            r, ff = model80.daa(a, f); exp += [0x0100 | r, 0x0200 | ff]
write("daa", "C5 DAA", asm, exp)
# INR / DCR
for name, fn, mn in (("inr", model80.inr, "INR"), ("dcr", model80.dcr, "DCR")):
    for form in ("b", "m"):
        asm, exp = [], []
        for v in range(256):
            for cy in (0, 1):
                for pat in PAT:
                    f = pat | cy; asm += setup(0x55, f)
                    if form == "b": asm += ["        MVI B,%d" % v, f"        {mn} B", "        MOV A,B", "        OUT 1"] + DUMP_F
                    else: asm += ["        MVI M,%d" % v, f"        {mn} M", "        MOV A,M", "        OUT 1"] + DUMP_F
                    r, ff = fn(v, f); exp += [0x0100 | r, 0x0200 | ff]
        write(f"{name}_{form}", f"C1 {mn} {form.upper()}", asm, exp)
# rotates
for mn in ("RLC", "RRC", "RAL", "RAR"):
    asm, exp = [], []
    for a in range(256):
        for cy in (0, 1):
            for pat in PAT:
                f = pat | cy; asm += setup(a, f) + [f"        {mn}", "        PUSH PSW", "        POP D", "        MOV A,D", "        OUT 1", "        MOV A,E", "        OUT 2"]
                r, ff = model80.rot(mn, a, f); exp += [0x0100 | r, 0x0200 | ff]
    write(mn.lower(), f"C1 {mn}", asm, exp)
print("wrote misc programs")
