#!/usr/bin/env python3
"""Generates the C1 ALU tests (spec 6.1, rows ADD..CMP and ADI..CPI) into build/gen/c1 (or argv[1]): alu_<op>_<form>.asm/.exp,
for the 8 ALU ops x 3 forms (register B, memory M, immediate) over a set of corner values for A and the operand
and both CY inputs (14 x 14 x 2 = 392 cases per program). A and F (as PUSH PSW pushes it) are written out through OUT 1 and OUT 2
after every case. Expected values come from tests/model80.py (written from spec 6)."""
import os, sys
sys.dont_write_bytecode = True
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here + '/..')
d = sys.argv[1] if len(sys.argv) > 1 else "build/gen/c1"; os.makedirs(d, exist_ok=True)
import model80
VALS = [0x00, 0x01, 0x0F, 0x10, 0x3E, 0x55, 0x7F, 0x80, 0x81, 0x8F, 0xAA, 0xF0, 0xF8, 0xFF]
OPS = ['ADD', 'ADC', 'SUB', 'SBB', 'ANA', 'XRA', 'ORA', 'CMP']
IMMN = {'ADD': 'ADI', 'ADC': 'ACI', 'SUB': 'SUI', 'SBB': 'SBI', 'ANA': 'ANI', 'XRA': 'XRI', 'ORA': 'ORI', 'CMP': 'CPI'}
for op in OPS:
    for form in ('reg', 'mem', 'imm'):
        asm = [f"; C1 {op} ({form}), generated by gen_alu.py", "        .org 0", "        LXI SP,0x8000", "        LXI H,0xC000"]
        exp = []
        for a in VALS:
            for b in VALS:
                for cy in (0, 1):
                    asm.append(f"        MVI A,{a}")
                    if form == 'reg': asm.append(f"        MVI B,{b}")
                    if form == 'mem': asm.append(f"        MVI M,{b}")
                    asm += ["        STC"] + ([] if cy else ["        CMC"])
                    asm.append({'reg': f"        {op} B", 'mem': f"        {op} M", 'imm': f"        {IMMN[op]} {b}"}[form])
                    asm += ["        PUSH PSW", "        POP D", "        MOV A,D", "        OUT 1", "        MOV A,E", "        OUT 2"]
                    r, f = model80.alu(op, a, b, cy)
                    exp += [0x0100 | r, 0x0200 | f]
        asm += ["end:    JMP end"]
        n = f"{d}/alu_{op.lower()}_{form}"
        import asm80; top = max(asm80.assemble(asm, True, {})); assert top < 0x7000, f"{n}: program reaches {top:#x}, into the data/stack area"
        open(n + ".asm", "w").write("\n".join(asm) + "\n")
        open(n + ".exp", "w").write("\n".join("%04X" % e for e in exp) + "\n")
print("wrote", len(OPS) * 3, "programs")
